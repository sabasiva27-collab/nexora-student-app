/**
 * Intelligent Department-to-Roadmap Resolver
 * Returns the customized learning roadmap for ANY college department!
 */
export function getRoadmapForDepartment(departmentName: string): StudentRoadmap {
  const deptLower = (departmentName || '').toLowerCase();

  // 1. Biomedical & Life Sciences HealthTech
  if (deptLower.includes('biomedical') || deptLower.includes('medical') || deptLower.includes('health') || deptLower.includes('bio-med')) {
    return BIOMEDICAL_ROADMAP;
  }

  // 2. Mechanical, Aerospace, Civil, Chemical, Automobile
  if (
    deptLower.includes('mechanical') ||
    deptLower.includes('aeronaut') ||
    deptLower.includes('aerospace') ||
    deptLower.includes('civil') ||
    deptLower.includes('chemical') ||
    deptLower.includes('cad')
  ) {
    return MECHANICAL_ROADMAP;
  }

  // 3. Commerce, Management & Finance
  if (
    deptLower.includes('commerce') ||
    deptLower.includes('b.com') ||
    deptLower.includes('bba') ||
    deptLower.includes('mba') ||
    deptLower.includes('business') ||
    deptLower.includes('finance') ||
    deptLower.includes('accounting')
  ) {
    return BUSINESS_ROADMAP;
  }

  // 4. Computing, Software, AI & IT
  if (
    deptLower.includes('computer') ||
    deptLower.includes('cse') ||
    deptLower.includes('information') ||
    deptLower.includes('it') ||
    deptLower.includes('data science') ||
    deptLower.includes('machine learning') ||
    deptLower.includes('ai') ||
    deptLower.includes('bca') ||
    deptLower.includes('mca') ||
    deptLower.includes('software')
  ) {
    return CSE_ROADMAP;
  }

  // 5. General STEM, Sciences, Pharmacy, Law, Agriculture, Arts, Other
  return GENERAL_STEM_ROADMAP;
}

